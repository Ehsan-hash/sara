// Phase 10: rename the companion and pick pronouns; built-in wording follows.
import assert from 'node:assert/strict';
import { test } from 'node:test';
import { join } from 'node:path';
import { personalize, toIdentity } from '../src/identity.ts';
import { memoryPrompt } from '../src/memory-worker.ts';
import { buildSystemPrompt, loadPersona, validatePersona } from '../src/persona.ts';
import { disclosureText } from '../src/safety.ts';
import { makeApp, ROOT, tempDir } from './helpers.ts';

const max = { name: 'Max', pronouns: 'he' } as const;
const river = { name: 'River', pronouns: 'they' } as const;

test('identity: Sara/she wording is unchanged by default', () => {
  const s = 'Sara is still working on this conversation. Wait for her or press Stop.';
  assert.equal(personalize(s), s);
  assert.equal(personalize(s, { name: 'Sara', pronouns: 'she' }), s);
});

test('identity: name and he/him, object vs possessive "her"', () => {
  assert.equal(personalize('Sara is still working on this conversation. Wait for her or press Stop.', max), 'Max is still working on this conversation. Wait for him or press Stop.');
  assert.equal(personalize("Her picture changes with her mood. Back to her pictures", max), 'His picture changes with his mood. Back to his pictures');
  assert.equal(personalize('Say "continue" to let her keep going.', max), 'Say "continue" to let him keep going.');
  assert.equal(personalize("What Sara learned from it stays in her memory unless you tick the box.", max), 'What Max learned from it stays in his memory unless you tick the box.');
  assert.equal(personalize('Sara can send you photos of herself. Her own portraits cost nothing.', max), 'Max can send you photos of himself. His own portraits cost nothing.');
  assert.equal(personalize("Sara's page", max), "Max's page");
  assert.equal(personalize('Make it yours: her look, voice and personality. Her reply and her laugh.', max), 'Make it yours: his look, voice and personality. His reply and his laugh.');
  assert.equal(personalize('Saratoga and Sarah stay', max), 'Saratoga and Sarah stay', 'whole words only');
});

test('identity: they/them with verb agreement', () => {
  assert.equal(personalize('She never sends a second message while the first is unanswered.', river), 'They never send a second message while the first is unanswered.');
  assert.equal(personalize("She stays in character, but she is software. If you sincerely ask whether she is an AI, she will tell you.", river), 'They stay in character, but they are software. If you sincerely ask whether they are an AI, they will tell you.');
  assert.equal(personalize("she's thinking; she watches, she tries, she misses you", river), "they're thinking; they watch, they try, they miss you");
  assert.equal(personalize('Wait until Sara finishes what she is doing.', river), 'Wait until River finishes what they are doing.');
  assert.equal(personalize('Read her replies aloud', river), 'Read their replies aloud');
  assert.equal(personalize('Approve it for her', river), 'Approve it for them');
});

test('identity: normalizes settings', () => {
  assert.deepEqual(toIdentity('', 'xx'), { name: 'Sara', pronouns: 'she' });
  assert.deepEqual(toIdentity(' Max ', 'he'), { name: 'Max', pronouns: 'he' });
});

test('identity: prompts, AI notice and memories follow a renamed companion', (t) => {
  const base = loadPersona(join(ROOT, 'persona', 'sara.json'));
  assert.equal(base.pronouns, 'she', 'default character is she/her');
  const river = validatePersona({ ...base, name: 'River', pronouns: 'they', appearance: 'a tall person in their thirties with short silver hair' });
  const prompt = buildSystemPrompt(river, { now: new Date('2026-10-24T20:00:00Z'), ownerName: 'Alex' });
  assert.match(prompt, /^You are River, 29\./);
  assert.match(prompt, /Live fully as River \(they\/them\): a person with their own history/);
  assert.match(prompt, /tell them plainly that you are an AI companion/, 'honesty rule always present');
  assert.equal(disclosureText('River'), 'River is an AI companion, not a human. Conversations are generated by AI models and may be inaccurate.');
  assert.throws(() => validatePersona({ ...base, appearance: 'a teenager with braces' }), /adult/);

  // Memory instructions: renamed, owner's name never rewritten (even if it is "Sara"), transcript untouched.
  const mp = memoryPrompt('Sara', '[#1 Sara 10/24] she said hi', { name: 'Max', pronouns: 'he' });
  assert.match(mp, /You maintain Max's long-term memory\. Below is part of a conversation between Sara and Max/);
  assert.match(mp, /things Max said about his own life \(not about Sara\) that he should stay consistent with/);
  assert.match(mp, /\[#1 Sara 10\/24\] she said hi/);

  // Renaming moves notes over; quotes stay as said.
  const { dir, cleanup } = tempDir();
  const app = makeApp(dir, { now: new Date('2026-10-24T20:00:00Z') });
  t.after(() => {
    app.store.close();
    cleanup();
  });
  const m = app.memory!.add({ kind: 'self', content: 'Sara said she watched The Thing.', conversationId: null, sourceMessageId: null, happenedOn: '2026-10-24', evidence: 'I watched The Thing, Sara-approved' });
  app.memory!.add({ kind: 'fact', content: 'Alex likes Saratoga water.', conversationId: null, sourceMessageId: null, happenedOn: '2026-10-24' });
  assert.equal(app.memory!.renameCompanion('Sara', 'River'), 1);
  const after = app.memory!.list({}).find((x) => x.id === m.id)!;
  assert.equal(after.content, 'River said she watched The Thing.');
  assert.equal(after.evidence, 'I watched The Thing, Sara-approved');
});

test('personalize: "her" before any/every/later is the object form', () => {
  const river = { name: 'River', pronouns: 'they' as const };
  assert.equal(personalize('Hands-free call: just talk, interrupt her any time', river), 'Hands-free call: just talk, interrupt them any time');
  assert.equal(personalize('Ask her later. Tell her everything. Her voice', river), 'Ask them later. Tell them everything. Their voice');
  assert.equal(personalize('interrupt her any time', { name: 'Max', pronouns: 'he' }), 'interrupt him any time');
  assert.equal(personalize('Also make her forget what she learned from it', river), 'Also make them forget what they learned from it');
});
